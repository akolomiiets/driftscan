// Package finding holds the domain types shared by every stage: Finding, Report and their enums.
package finding

import (
	"encoding/json"
	"fmt"
	"strings"
	"time"
)

type Kind string

const (
	KindDrift     Kind = "drift"
	KindPending   Kind = "pending"
	KindScanError Kind = "scan_error"
)

type Status string

const (
	StatusNew        Status = "new"
	StatusPersisting Status = "persisting"
	StatusChanged    Status = "changed"
	StatusResolved   Status = "resolved"
	StatusUnknown    Status = "unknown"
)

// Severity is ordered: a higher value needs a human sooner.
type Severity int

const (
	SeverityInfo Severity = iota
	SeverityLow
	SeverityMedium
	SeverityHigh
	SeverityCritical
)

var severityNames = []string{"info", "low", "medium", "high", "critical"}

func (s Severity) String() string {
	if s < 0 || int(s) >= len(severityNames) {
		return fmt.Sprintf("severity(%d)", int(s))
	}
	return severityNames[s]
}

func ParseSeverity(v string) (Severity, error) {
	for i, n := range severityNames {
		if strings.EqualFold(v, n) {
			return Severity(i), nil
		}
	}
	return 0, fmt.Errorf("unknown severity %q (want one of %s)", v, strings.Join(severityNames, ", "))
}

func (s Severity) MarshalText() ([]byte, error) { return []byte(s.String()), nil }

func (s *Severity) UnmarshalText(b []byte) error {
	v, err := ParseSeverity(string(b))
	if err != nil {
		return err
	}
	*s = v
	return nil
}

// Values of Finding.AckReason.
const (
	AckIgnoreChanges = "ignore_changes"
	AckNotReverted   = "not_reverted"
)

// Finding is one reported fact about one resource, or about a whole Root for a Scan error.
// It never carries attribute values (ADR-0002).
type Finding struct {
	Root     string   `json:"root"`
	Address  string   `json:"address,omitempty"`
	Type     string   `json:"type,omitempty"`
	Kind     Kind     `json:"kind"`
	Actions  []string `json:"actions,omitempty"`
	Paths    []string `json:"paths,omitempty"`
	Severity Severity `json:"severity"`
	Status   Status   `json:"status,omitempty"`
	// Acknowledged marks drift only on attributes that Terraform will not revert: listed in
	// lifecycle.ignore_changes or that the plan would not change.
	Acknowledged bool `json:"acknowledged,omitempty"`
	// AckReason says why: AckIgnoreChanges or AckNotReverted.
	AckReason string `json:"ack_reason,omitempty"`
	Message   string `json:"message,omitempty"`
	// File and Line point at the resource or module block, else the backend block (slash path).
	File string `json:"file,omitempty"`
	Line int    `json:"line,omitempty"`
	// SeenCount is how many consecutive Scans have reported this Finding, this one included.
	SeenCount int       `json:"seen_count,omitempty"`
	FirstSeen time.Time `json:"first_seen,omitzero"`
	// Owner and OwnerSource ("codeowners" or "git") are set by driftscan enrich.
	Owner       string `json:"owner,omitempty"`
	OwnerSource string `json:"owner_source,omitempty"`
	// ChangedBy, ChangedAt and ChangeEvent are the newest CloudTrail write event, set by driftscan
	// enrich -cloudtrail.
	ChangedBy   string    `json:"changed_by,omitempty"`
	ChangedAt   time.Time `json:"changed_at,omitzero"`
	ChangeEvent string    `json:"change_event,omitempty"`
	// Advice, AdviceAction and AdviceIgnoreRule are AI-generated by driftscan advise.
	Advice           string `json:"advice,omitempty"`
	AdviceAction     string `json:"advice_action,omitempty"`
	AdviceIgnoreRule string `json:"advice_ignore_rule,omitempty"`
}

// Key is the Finding identity across Scans: Root + address + kind (ADR-0001).
func (f Finding) Key() string {
	return f.Root + "\x00" + f.Address + "\x00" + string(f.Kind)
}

// Active reports whether the Finding still describes a current problem.
func (f Finding) Active() bool {
	return f.Status != StatusResolved
}

type RootOutcome string

const (
	RootClean   RootOutcome = "clean"
	RootDrifted RootOutcome = "drifted"
	RootError   RootOutcome = "error"
	RootSkipped RootOutcome = "skipped"
)

type RootResult struct {
	Path     string        `json:"path"`
	Outcome  RootOutcome   `json:"outcome"`
	Duration time.Duration `json:"duration_ns"`
	// FailCount is consecutive Scans in which this Root had a Scan error.
	FailCount int `json:"fail_count,omitempty"`
}

const ReportVersion = 1

// Report is the full result of a Scan, also used as the Baseline of the next one.
type Report struct {
	Version   int           `json:"version"`
	Tool      string        `json:"tool"`
	StartedAt time.Time     `json:"started_at"`
	Duration  time.Duration `json:"duration_ns"`
	// Compared is false for a raw shard Report and for a first Scan with no Baseline.
	Compared bool `json:"compared"`
	// Shard is "i/n" on a raw shard Report. Partial means some Roots were not scanned (a shard
	// alone, or a merge missing shards), so Baseline Findings of absent Roots are unknown, not resolved.
	Shard    string       `json:"shard,omitempty"`
	Partial  bool         `json:"partial,omitempty"`
	Roots    []RootResult `json:"roots"`
	Findings []Finding    `json:"findings"`
}

func (r Report) Marshal() ([]byte, error) {
	return json.MarshalIndent(r, "", "  ")
}

func Unmarshal(b []byte) (Report, error) {
	var r Report
	if err := json.Unmarshal(b, &r); err != nil {
		return Report{}, fmt.Errorf("parse report: %w", err)
	}
	if r.Version != ReportVersion {
		return Report{}, fmt.Errorf("unsupported report version %d (want %d)", r.Version, ReportVersion)
	}
	return r, nil
}
